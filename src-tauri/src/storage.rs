//! Files in the app-data folder: wallpaper, card art / custom icons, dropped images.
#![allow(unused_imports)]
use crate::util::*;
use std::{
    collections::HashSet,
    fs,
    path::{Path, PathBuf},
    process::{Command, Stdio},
    time::{Duration, Instant},
};
use tauri::Manager;

pub(crate) fn wallpaper_path(app: &tauri::AppHandle) -> Result<PathBuf, String> {
    let base = app.path().app_data_dir().map_err(|e| e.to_string())?;
    Ok(base.join("custom-wallpaper"))
}

pub(crate) fn card_art_dir(app: &tauri::AppHandle) -> Result<PathBuf, String> {
    let base = app.path().app_data_dir().map_err(|e| e.to_string())?;
    Ok(base.join("card-art"))
}

/// Card art file names are generated by Aether: <shortcut-id>-<timestamp>.<ext>
pub(crate) fn valid_card_file(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 120
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '.')
        && !name.starts_with('.')
        && !name.contains("..")
}

#[tauri::command]
pub async fn set_wallpaper(app: tauri::AppHandle, source: String) -> Result<(), String> {
    blocking(move || {
        let path = PathBuf::from(source);
        let extension = path
            .extension()
            .and_then(|x| x.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        if !["png", "jpg", "jpeg", "webp", "gif", "bmp"].contains(&extension.as_str()) {
            return Err("Unsupported image type".to_string());
        }
        let meta = fs::metadata(&path).map_err(|e| e.to_string())?;
        if !meta.is_file() || meta.len() > MAX_IMAGE_BYTES {
            return Err("Image must be a file under 12 MB".into());
        }
        let contents = fs::read(&path).map_err(|e| e.to_string())?;
        if image_extension(&contents).is_none() {
            return Err("Invalid or unsupported image data".into());
        }
        write_atomic(&wallpaper_path(&app)?, &contents)
    })
    .await?
}

/// v0.10: returns raw bytes (ArrayBuffer in JS) instead of a JSON number array,
/// which was ~3-4x larger than the image and slow to parse on startup.
#[tauri::command]
pub async fn load_wallpaper(app: tauri::AppHandle) -> Result<tauri::ipc::Response, String> {
    blocking(move || {
        let path = wallpaper_path(&app)?;
        if !path.exists() {
            return Ok(tauri::ipc::Response::new(Vec::<u8>::new()));
        }
        let meta = fs::metadata(&path).map_err(|e| e.to_string())?;
        if meta.len() > MAX_IMAGE_BYTES {
            return Err("Wallpaper file is too large".to_string());
        }
        fs::read(path)
            .map(tauri::ipc::Response::new)
            .map_err(|e| e.to_string())
    })
    .await?
}

#[tauri::command]
pub async fn clear_wallpaper(app: tauri::AppHandle) -> Result<(), String> {
    blocking(move || {
        let path = wallpaper_path(&app)?;
        if path.exists() {
            fs::remove_file(path).map_err(|e| e.to_string())?;
        }
        Ok(())
    })
    .await?
}

/// Absolute card-art folder, used by the UI to build asset:// URLs.
#[tauri::command]
pub fn card_art_folder(app: tauri::AppHandle) -> Result<String, String> {
    let dir = card_art_dir(&app)?;
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir.to_string_lossy().into_owned())
}

/// Save card artwork (base64 image data) and return the generated file name.
#[tauri::command]
pub async fn save_card_art(
    app: tauri::AppHandle,
    id: String,
    data: String,
) -> Result<String, String> {
    blocking(move || {
        use base64::Engine;
        if id.is_empty()
            || id.len() > 64
            || !id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
        {
            return Err("Invalid shortcut id".to_string());
        }
        let payload = data.split_once(',').map(|(_, b)| b).unwrap_or(&data);
        if payload.len() as u64 > MAX_IMAGE_BYTES * 2 {
            return Err("Card image is too large".into());
        }
        let bytes = base64::engine::general_purpose::STANDARD
            .decode(payload.trim())
            .map_err(|_| "Card image data is invalid".to_string())?;
        let ext =
            image_extension(&bytes).ok_or_else(|| "Unsupported card image format".to_string())?;
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_millis())
            .unwrap_or(0);
        let name = format!("{}-{}.{}", id, stamp, ext);
        write_atomic(&card_art_dir(&app)?.join(&name), &bytes)?;
        Ok(name)
    })
    .await?
}

/// Read card artwork back as raw bytes (used to embed images in backups).
#[tauri::command]
pub async fn read_card_art(
    app: tauri::AppHandle,
    file: String,
) -> Result<tauri::ipc::Response, String> {
    blocking(move || {
        if !valid_card_file(&file) {
            return Err("Invalid card art file".to_string());
        }
        let path = card_art_dir(&app)?.join(&file);
        let meta = fs::metadata(&path).map_err(|e| e.to_string())?;
        if meta.len() > MAX_IMAGE_BYTES {
            return Err("Card image is too large".to_string());
        }
        fs::read(path)
            .map(tauri::ipc::Response::new)
            .map_err(|e| e.to_string())
    })
    .await?
}

#[tauri::command]
pub async fn delete_card_art(app: tauri::AppHandle, file: String) -> Result<(), String> {
    blocking(move || {
        if !valid_card_file(&file) {
            return Err("Invalid card art file".to_string());
        }
        let path = card_art_dir(&app)?.join(&file);
        if path.exists() {
            fs::remove_file(path).map_err(|e| e.to_string())?;
        }
        Ok(())
    })
    .await?
}

/// Remove card-art files no shortcut references any more (e.g. after deletions).
#[tauri::command]
pub async fn prune_card_art(app: tauri::AppHandle, keep: Vec<String>) -> Result<u32, String> {
    blocking(move || {
        let dir = card_art_dir(&app)?;
        let keep: HashSet<String> = keep.into_iter().map(|k| k.to_lowercase()).collect();
        let Ok(entries) = fs::read_dir(&dir) else {
            return Ok(0);
        };
        let mut removed = 0;
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            if entry.path().is_file()
                && valid_card_file(&name)
                && !keep.contains(&name.to_lowercase())
            {
                if fs::remove_file(entry.path()).is_ok() {
                    removed += 1;
                }
            }
        }
        Ok(removed)
    })
    .await?
}

/// Editor: read an image the user dropped onto the window. Only validated image
/// files under 12 MB are returned; the original file is never modified.
#[tauri::command]
pub async fn read_image_file(path: String) -> Result<tauri::ipc::Response, String> {
    blocking(move || {
        let path = PathBuf::from(path);
        let extension = path
            .extension()
            .and_then(|x| x.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        if !["png", "jpg", "jpeg", "webp", "gif", "bmp"].contains(&extension.as_str()) {
            return Err("Drop a PNG, JPG, WebP, GIF or BMP image.".to_string());
        }
        let meta = fs::metadata(&path).map_err(|e| e.to_string())?;
        if !meta.is_file() || meta.len() > MAX_IMAGE_BYTES {
            return Err("Image must be a file under 12 MB".into());
        }
        let contents = fs::read(&path).map_err(|e| e.to_string())?;
        if image_extension(&contents).is_none() {
            return Err("Invalid or unsupported image data".into());
        }
        Ok(tauri::ipc::Response::new(contents))
    })
    .await?
}

/// Settings → About: where Aether keeps images, icons and the wallpaper.
#[tauri::command]
pub fn app_data_folder(app: tauri::AppHandle) -> Result<String, String> {
    let dir = app.path().app_data_dir().map_err(|e| e.to_string())?;
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir.to_string_lossy().into_owned())
}

#[tauri::command]
pub async fn open_app_data_folder(app: tauri::AppHandle) -> Result<(), String> {
    blocking(move || {
        let dir = app.path().app_data_dir().map_err(|e| e.to_string())?;
        fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        #[cfg(target_os = "windows")]
        {
            Command::new("explorer.exe")
                .arg(&dir)
                .spawn()
                .map(|_| ())
                .map_err(|e| e.to_string())
        }
        #[cfg(not(target_os = "windows"))]
        {
            let _ = dir;
            Err("File Explorer is available on Windows only".to_string())
        }
    })
    .await?
}
